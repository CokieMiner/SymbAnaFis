pub(super) const fn get_precision() -> u32 {
    24
} // f32 mantissa bits

// --- Construction & conversion ---

#[inline]
#[allow(
    clippy::cast_precision_loss,
    reason = "Lossy int-to-float; caller must restrict magnitude for exactness"
)]
pub(super) fn from_int(value: &IntType) -> BackingFloat {
    *value as f32
}

#[inline]
pub(super) const fn from_f32(value: f32) -> BackingFloat {
    value
}

#[inline]
#[allow(clippy::cast_possible_truncation, reason = "Lossy f64→f32 is intended")]
pub(super) const fn from_f64(value: f64) -> BackingFloat {
    value as f32
}

#[inline]
#[allow(clippy::cast_precision_loss, reason = "Intended lossy conversion")]
#[allow(clippy::cast_possible_truncation, reason = "Lossy i64→f32 is intended")]
pub(super) const fn from_i64(value: i64) -> BackingFloat {
    value as f32
}

#[allow(
    clippy::cast_precision_loss,
    reason = "i32::MAX is not exactly representable in f32; bounds check is approximate but safe"
)]
pub(super) fn to_int(value: &BackingFloat) -> Option<IntType> {
    let v = *value;
    if v.fract() != 0.0 || v < i32::MIN as f32 || v >= i32::MAX as f32 {
        return None;
    }
    #[allow(
        clippy::cast_possible_truncation,
        reason = "Bounds just checked, f32→i32 is safe"
    )]
    {
        Some(v as i32)
    }
}

pub(super) fn nan() -> BackingFloat {
    f32::NAN
}

